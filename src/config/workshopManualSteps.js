export function getManualSteps(genreId) {
  return WORKSHOP_MANUAL_STEPS[genreId] || null;
}

/** 一覧用カード定義（準備 + Step1〜5 + アップロード） */
export function getWorkshopStepCards(genreId) {
  const steps = getManualSteps(genreId);
  if (!steps) return null;

  return [
    {
      id: 'setup',
      kind: 'setup',
      badge: '準備',
      shortTitle: 'フォルダをダウンロード',
      title: 'まずはフォルダをダウンロード',
    },
    ...steps.map((step, i) => ({
      id: step.id,
      kind: 'prompt',
      badge: `Step ${i + 1}`,
      shortTitle: step.shortTitle,
      title: step.title,
      stepIndex: i,
      data: step,
    })),
    {
      id: 'upload',
      kind: 'upload',
      badge: '発表',
      shortTitle: 'ゲームをアップロード',
      title: '完成したフォルダをアップしてみんなで遊ぼう',
    },
  ];
}
